export function addSectionIntroductions(lectures) {
  for (const lecture of lectures) {
    if (lecture.chapter !== 1 && lecture.chapter !== 2) continue;
    lecture.sections.forEach((section, index) => {
      const key = `${lecture.chapter}-${lecture.number}-${index + 1}`;
      const introduction = sectionIntroductions[key];
      if (!introduction) return;
      const paragraph = `<p>${introduction}</p>`;
      if (!section.html.startsWith(paragraph)) section.html = paragraph + section.html;
    });
  }
}
