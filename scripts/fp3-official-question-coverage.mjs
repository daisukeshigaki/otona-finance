export function assertOfficialCoverage(lectures){
  for(const [id,term] of officialCoverageTerms){
    const lecture=byId(lectures,id);
    const corpus=[lecture.lead,...lecture.sections.map(x=>x.title+x.html),...lecture.questions.flatMap(x=>[x.title,x.data,x.ask,x.answer]),...lecture.recap].join('\n');
    if(!corpus.includes(term))throw new Error(`Official-question coverage missing: ${id} ${term}`);
  }
}
