const byId=(lectures,id)=>{
  const [chapter,number]=id.split('-').map(Number);
  const lecture=lectures.find(x=>x.chapter===chapter&&x.number===number);
  if(!lecture)throw new Error(`Missing FP3 lecture ${id}`);
  return lecture;
};

function addSection(lectures,id,title,html){
  byId(lectures,id).sections.push({title,html});
}

function replaceCheck(lectures,id,question){
  const lecture=byId(lectures,id);
  lecture.questions[1]={...question,officialCoverage:true,original:true};
}

function addSource(lectures,id,name,url){
  const lecture=byId(lectures,id);
  if(!lecture.sources.some(x=>x[1]===url))lecture.sources.push([name,url]);
}

